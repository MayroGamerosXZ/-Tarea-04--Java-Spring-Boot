package com.thundermax.ferreteria.model.enums;

/**
 * Unidades en las que una ferretería vende sus productos.
 * Ej.: el cable se vende por METRO, los clavos por LIBRA y la pintura por GALON.
 */
public enum UnidadMedida {
    UNIDAD,
    METRO,
    LIBRA,
    KILOGRAMO,
    GALON,
    CUBETA,
    CAJA,
    BOLSA,
    ROLLO
}
